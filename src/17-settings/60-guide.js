/** @type {string|null} 正看的那一篇；空即目录 */
let guideTopic = null;
const guideText = text =>
  escapeHtml(text)
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
function guideSettingsHtml() {
  const index = GUIDE.findIndex(topic => topic.id === guideTopic);
  if (index < 0)
    return `<div id="guidePage"><div class="settings-head">${brushIcon("guide", "settings-mark")}<h2>${t(`文档`)}</h2><span class="settings-meta">v${escapeHtml(bootstrap.version || APP_VERSION)}</span></div><div class="guide-toc">${GUIDE.map(
      (topic, i) =>
        `<button type="button" class="guide-row" data-guide="${topic.id}"><span class="guide-juan">${t`卷${chineseNumber(i + 1)}`}</span><span class="guide-title">${escapeHtml(topic.title)}</span><span class="guide-lead-line" aria-hidden="true"></span><span class="guide-gist">${escapeHtml(topic.lead)}</span></button>`
    ).join("")}</div></div>`;
  const topic = GUIDE[index],
    prev = GUIDE[index - 1],
    next = GUIDE[index + 1];
  return `<div id="guidePage" class="guide-doc"><div class="guide-top"><button type="button" class="guide-back" data-guide="">${t(`‹ 目录`)}</button><span>·</span><span>${t`卷${chineseNumber(index + 1)} · ${escapeHtml(topic.title)}`}</span><span class="guide-fish" aria-hidden="true">${t(`◆ 言 · 文档`)}</span></div><h2>${escapeHtml(topic.lead)}</h2><p class="guide-summary">${guideText(topic.summary)}</p><div class="guide-steps">${topic.steps
    .map(
      (step, i) =>
        `<section class="guide-step"><div class="guide-main"><h4><span class="guide-no" aria-hidden="true">${chineseNumber(i + 1)}</span>${escapeHtml(step.h)}</h4><p>${guideText(step.body)}</p></div>${
          step.note ? `<aside class="guide-note"><b>${escapeHtml(step.noteLabel || t("眉批"))}</b>${guideText(step.note)}</aside>` : ""
        }</section>`
    )
    .join(
      ""
    )}</div><div class="guide-pager">${prev ? `<button type="button" data-guide="${prev.id}">${t`‹ 卷${chineseNumber(index)} · ${escapeHtml(prev.title)}`}</button>` : "<span></span>"}${next ? `<button type="button" data-guide="${next.id}">${t`卷${chineseNumber(index + 2)} · ${escapeHtml(next.title)} ›`}</button>` : "<span></span>"}</div></div>`;
}
function bindGuideEvents() {
  $("#guidePage").addEventListener("click", event => {
    const target = /** @type {HTMLElement} */ (event.target).closest("[data-guide]");
    if (!target) return;
    guideTopic = target.dataset.guide || null;
    renderSettings();
    $("#settingsContent").scrollTop = 0;
  });
}
